using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace VS.Localization.Generator
{
    /// <summary>Generates dependency-free C# from a deliberately small YAML mapping format.</summary>
    public static class LocalizationGenerator
    {
        public const string Header = "// <auto-generated by VS.Localization>";
        private static readonly Regex Identifier = new Regex(@"^[A-Za-z_][A-Za-z0-9_]*$");
        private static readonly Regex LocalePattern = new Regex(@"^[a-zA-Z]{2,8}(?:-[a-zA-Z0-9]{1,8})*$");

        private sealed class Entry
        {
            public string Name;
            public readonly Dictionary<string, string> Translations = new Dictionary<string, string>();
        }

        public static CompilationUnitSyntax Generate(string yaml, string className = "Strings")
        {
            if (yaml == null) throw new ArgumentNullException(nameof(yaml));
            if (!Identifier.IsMatch(className) || className == "Locale")
                throw new FormatException("The catalog filename must be a C# identifier other than Locale.");
            var entries = Parse(yaml, className);
            var locales = entries.SelectMany(e => e.Translations.Keys).Distinct().ToArray();
            var fallback = locales.Contains("en") ? "en" : locales[0];
            foreach (var entry in entries)
                if (!entry.Translations.ContainsKey(fallback))
                    throw new FormatException($"{entry.Name}: missing fallback translation '{fallback}'.");

            var members = new List<MemberDeclarationSyntax>
            {
                FieldDeclaration(VariableDeclaration(CsType("string"))
                    .AddVariables(VariableDeclarator("_locale")))
                    .AddModifiers(Token(SyntaxKind.PrivateKeyword), Token(SyntaxKind.ReadOnlyKeyword)),
                PropertyDeclaration(CsType("string"), "Locale")
                    .AddModifiers(Token(SyntaxKind.PublicKeyword))
                    .WithExpressionBody(ArrowExpressionClause(BinaryExpression(SyntaxKind.CoalesceExpression,
                        Id("_locale"), Literal(fallback))))
                    .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                LocaleConstructor(className, locales, fallback)
            };

            foreach (var entry in entries)
            {
                var parameters = new List<string>();
                var types = new Dictionary<string, string>(StringComparer.Ordinal);
                Expression(entry.Translations[fallback], parameters, types);
                foreach (var translation in entry.Translations)
                {
                    var actual = new List<string>();
                    Expression(translation.Value, actual, types, true);
                    if (!new HashSet<string>(parameters).SetEquals(actual))
                        throw new FormatException($"{entry.Name}/{translation.Key}: placeholders must match the '{fallback}' translation.");
                }
                var sections = new List<SwitchSectionSyntax>();
                foreach (var translation in entry.Translations)
                    if (translation.Key != fallback)
                        sections.Add(SwitchSection().AddLabels(CaseSwitchLabel(Literal(translation.Key)))
                            .AddStatements(ReturnStatement(Expression(translation.Value, new List<string>(), types, true))));
                sections.Add(SwitchSection().AddLabels(DefaultSwitchLabel())
                    .AddStatements(ReturnStatement(Expression(entry.Translations[fallback], new List<string>(), types, true))));
                var body = Block(SwitchStatement(Member(ThisExpression(), "Locale")).AddSections(sections.ToArray()));
                if (parameters.Count == 0)
                    members.Add(PropertyDeclaration(CsType("string"), Escaped(entry.Name))
                        .AddModifiers(Token(SyntaxKind.PublicKeyword))
                        .AddAccessorListAccessors(AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithBody(body)));
                else
                    members.Add(MethodDeclaration(CsType("string"), Escaped(entry.Name))
                        .AddModifiers(Token(SyntaxKind.PublicKeyword))
                        .AddParameterListParameters(parameters.Select(p => Parameter(Escaped(p)).WithType(CsType(types[p]))).ToArray())
                        .WithBody(body));
            }
            var declaration = ClassDeclaration(Escaped(className))
                .AddModifiers(Token(SyntaxKind.InternalKeyword)).AddMembers(members.ToArray());
            return CompilationUnit().AddMembers(declaration)
                .WithLeadingTrivia(Comment(Header), EndOfLine("\n"))
                .NormalizeWhitespace(eol: "\n").WithTrailingTrivia(EndOfLine("\n"));
        }

        private static ConstructorDeclarationSyntax LocaleConstructor(string className, string[] locales, string fallback)
        {
            var normalized = Call(Member(Call(Member(Call(Member(
                ParenthesizedExpression(BinaryExpression(SyntaxKind.CoalesceExpression, Id("locale"), Literal(""))),
                "Trim")), "Replace"), LiteralExpression(SyntaxKind.CharacterLiteralExpression, Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Literal('_')),
                LiteralExpression(SyntaxKind.CharacterLiteralExpression, Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Literal('-'))), "ToLowerInvariant"));
            var sections = locales.Select(locale => SwitchSection().AddLabels(CaseSwitchLabel(Literal(locale)))
                .AddStatements(Assign(Id("_locale"), Id("candidate")), ReturnStatement())).ToArray();
            return ConstructorDeclaration(Escaped(className))
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .AddParameterListParameters(Parameter(IdentifierToken("locale")).WithType(CsType("string")))
                .WithBody(Block(
                    Var("candidate", normalized),
                    WhileStatement(BinaryExpression(SyntaxKind.GreaterThanExpression, Member(Id("candidate"), "Length"), Number(0)),
                        Block(SwitchStatement(Id("candidate")).AddSections(sections),
                            Var("separator", Call(Member(Id("candidate"), "LastIndexOf"),
                                LiteralExpression(SyntaxKind.CharacterLiteralExpression, Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Literal('-')))),
                            IfStatement(BinaryExpression(SyntaxKind.LessThanExpression, Id("separator"), Number(0)), BreakStatement()),
                            Assign(Id("candidate"), Call(Member(Id("candidate"), "Substring"), Number(0), Id("separator"))))),
                    Assign(Id("_locale"), Literal(fallback))));
        }

        private static SyntaxToken IdentifierToken(string name) => Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Identifier(name);
        private static SyntaxToken Escaped(string name) => IdentifierToken("@" + name);
        private static IdentifierNameSyntax Id(string name) => IdentifierName(name);
        private static TypeSyntax CsType(string type) => PredefinedType(Token(SyntaxFacts.GetKeywordKind(type)));
        private static ExpressionSyntax Number(int value) => LiteralExpression(SyntaxKind.NumericLiteralExpression, Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Literal(value));
        private static MemberAccessExpressionSyntax Member(ExpressionSyntax value, string name) =>
            MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, value, Id(name));
        private static InvocationExpressionSyntax Call(ExpressionSyntax method, params ExpressionSyntax[] args) =>
            InvocationExpression(method, ArgumentList(SeparatedList(args.Select(Argument))));
        private static StatementSyntax Assign(ExpressionSyntax left, ExpressionSyntax right) =>
            ExpressionStatement(AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, left, right));
        private static LocalDeclarationStatementSyntax Var(string name, ExpressionSyntax value) =>
            LocalDeclarationStatement(VariableDeclaration(Id("var")).AddVariables(VariableDeclarator(name).WithInitializer(EqualsValueClause(value))));

        private static List<Entry> Parse(string yaml, string className)
        {
            var result = new List<Entry>();
            var names = new HashSet<string>(StringComparer.Ordinal);
            Entry current = null;
            var lines = yaml.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
            for (var i = 0; i < lines.Length; i++)
            {
                var line = i == 0 ? lines[i].TrimStart('\uFEFF') : lines[i];
                if (string.IsNullOrWhiteSpace(line) || line.TrimStart().StartsWith("#", StringComparison.Ordinal)) continue;
                try
                {
                    var indent = line.TakeWhile(c => c == ' ').Count();
                    if (line.IndexOf('\t') >= 0) throw new FormatException("Use spaces instead of tabs (or \\t inside a quoted string).");
                    var colon = line.IndexOf(':');
                    if (colon < indent) throw new FormatException("Expected key: value.");
                    var key = line.Substring(indent, colon - indent).Trim();
                    var value = line.Substring(colon + 1).Trim();
                    if (indent == 0)
                    {
                        if (!Identifier.IsMatch(key)) throw new FormatException("Entry keys must be C# identifiers, e.g. welcome_back.");
                        var name = string.Concat(key.Split('_').Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p.Substring(1)));
                        if (name.Length == 0 || !Identifier.IsMatch(name)) throw new FormatException("The entry key must contain a letter.");
                        if (name == className || name == "Locale" || name == "Equals" || name == "GetHashCode" || name == "GetType" || name == "ToString" || name == "ReferenceEquals" || name == "MemberwiseClone" || name == "Finalize")
                            throw new FormatException("Reserved entry name: " + name);
                        if (value.Length > 0 && !value.StartsWith("#", StringComparison.Ordinal)) throw new FormatException("An entry must contain an indented locale mapping.");
                        if (!names.Add(name)) throw new FormatException("Duplicate generated member: " + name);
                        current = new Entry { Name = name };
                        result.Add(current);
                    }
                    else
                    {
                        if (indent != 2 || current == null) throw new FormatException("Translations must be indented by exactly two spaces beneath an entry.");
                        if (!LocalePattern.IsMatch(key)) throw new FormatException("Expected a locale code such as en, ru or pt-BR.");
                        key = key.ToLowerInvariant();
                        if (current.Translations.ContainsKey(key)) throw new FormatException("Duplicate locale: " + key);
                        current.Translations.Add(key, Scalar(value));
                    }
                }
                catch (FormatException exception) { throw new FormatException($"Line {i + 1}: {exception.Message}", exception); }
            }
            if (result.Count == 0) throw new FormatException("The catalog is empty.");
            foreach (var entry in result)
                if (entry.Translations.Count == 0) throw new FormatException(entry.Name + ": no translations.");
            return result;
        }

        private static string Scalar(string value)
        {
            if (value.Length == 0 || value[0] == '#') throw new FormatException("Use \"\" for an empty translation.");
            if (value[0] != '\'' && value[0] != '"')
            {
                var comment = value.IndexOf(" #", StringComparison.Ordinal);
                if (comment >= 0) value = value.Substring(0, comment).TrimEnd();
                if (value.IndexOf(": ", StringComparison.Ordinal) >= 0 || value.EndsWith(":", StringComparison.Ordinal) || "|>!&*{[%@`".IndexOf(value[0]) >= 0 || value == "-" || value.StartsWith("- ", StringComparison.Ordinal) || value.StartsWith("? ", StringComparison.Ordinal))
                    throw new FormatException("Quote this translation. Nested YAML, aliases and block scalars are not supported.");
                return value;
            }
            var quote = value[0];
            var result = new StringBuilder();
            for (var i = 1; i < value.Length; i++)
            {
                var c = value[i];
                if (c == quote)
                {
                    if (quote == '\'' && i + 1 < value.Length && value[i + 1] == '\'') { result.Append('\''); i++; continue; }
                    var tail = value.Substring(i + 1);
                    if (tail.Length > 0 && !(char.IsWhiteSpace(tail[0]) && (tail.Trim().Length == 0 || tail.TrimStart().StartsWith("#", StringComparison.Ordinal))))
                        throw new FormatException("Unexpected text after a quoted translation.");
                    return result.ToString();
                }
                if (quote == '"' && c == '\\')
                {
                    if (++i >= value.Length) throw new FormatException("Incomplete escape sequence.");
                    switch (value[i])
                    {
                        case 'n': result.Append('\n'); break;
                        case 'r': result.Append('\r'); break;
                        case 't': result.Append('\t'); break;
                        case '"': result.Append('"'); break;
                        case '\\': result.Append('\\'); break;
                        default: throw new FormatException("Supported escapes: \\n, \\r, \\t, \\\\, \\\".");
                    }
                }
                else result.Append(c);
            }
            throw new FormatException("Unclosed quoted translation.");
        }

        private static ExpressionSyntax Expression(string value, List<string> parameters, Dictionary<string, string> types, bool validate = false)
        {
            var parts = new List<ExpressionSyntax>();
            var literal = new StringBuilder();
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                if ((c == '{' || c == '}') && i + 1 < value.Length && value[i + 1] == c) { literal.Append(c); i++; continue; }
                if (c == '}') throw new FormatException("Unmatched }. Use }} for a literal brace.");
                if (c != '{') { literal.Append(c); continue; }
                var end = value.IndexOf('}', i + 1);
                if (end < 0) throw new FormatException("Unclosed placeholder.");
                var placeholder = value.Substring(i + 1, end - i - 1).Trim();
                var declaration = placeholder.Split(':');
                var name = declaration[0].Trim();
                if (declaration.Length > 2) throw new FormatException("Use {name} or {name:type}.");
                string knownType;
                var type = declaration.Length == 2 ? declaration[1].Trim() :
                    types.TryGetValue(name, out knownType) ? knownType : "string";
                if (!new[] { "string", "int", "long", "float", "double", "decimal", "bool" }.Contains(type))
                    throw new FormatException("Unsupported placeholder type: " + type);
                if (types.TryGetValue(name, out knownType) && knownType != type)
                    throw new FormatException("Conflicting types for parameter " + name);
                if (validate && !types.ContainsKey(name))
                    throw new FormatException("Unexpected placeholder: " + name);
                if (!validate) types[name] = type;
                if (!Identifier.IsMatch(name)) throw new FormatException("Invalid placeholder: {" + name + "}. Use {name}.");
                if (!parameters.Contains(name)) parameters.Add(name);
                if (literal.Length > 0) { parts.Add(Literal(literal.ToString())); literal.Clear(); }
                parts.Add(type == "string" ? (ExpressionSyntax)IdentifierName(Escaped(name)) :
                    Call(Member(ParseName("global::System.Convert"), "ToString"), IdentifierName(Escaped(name)),
                        Member(ParseName("global::System.Globalization.CultureInfo"), "InvariantCulture")));
                i = end;
            }
            if (literal.Length > 0) parts.Add(Literal(literal.ToString()));
            if (parts.Count == 0) return Literal("");
            // Concat also gives placeholder-only translations consistent null-as-empty semantics.
            return parameters.Count == 0 ? parts[0] : Call(Member(CsType("string"), "Concat"), parts.ToArray());
        }

        private static LiteralExpressionSyntax Literal(string value) =>
            LiteralExpression(SyntaxKind.StringLiteralExpression, Microsoft.CodeAnalysis.CSharp.SyntaxFactory.Literal(value));
    }
}
